rmSync('plugins', { recursive: true, force: true })
for (const plugin of PLUGINS) {
  const dir = `plugins/${plugin.name}`
  mkdirSync(`${dir}/.claude-plugin`, { recursive: true })
  mkdirSync(`${dir}/hooks`, { recursive: true })
  mkdirSync(`${dir}/types`, { recursive: true })
  const rename = text => text.replaceAll("'olive-theme'", `'${plugin.name}'`)
  for (const file of plugin.files) {
    const text = readFileSync(`hooks/${file}`, 'utf8')
    writeFileSync(`${dir}/hooks/${file}`, file.endsWith('.js') ? text : rename(text))
  }
  writeFileSync(`${dir}/hooks/register.tsx`, rename(plugin.register(plugin.name)))
  writeFileSync(`${dir}/hooks/hooks.json`, '{ "modules": ["./register.tsx"] }\n')
  writeFileSync(`${dir}/types/index.d.ts`, rename(readFileSync('types/index.d.ts', 'utf8')))
  writeFileSync(`${dir}/tsconfig.json`, '{\n  "extends": "./.claude-plugin/types/tsconfig.json"\n}\n')
  if (plugin.sounds) cpSync('sounds', `${dir}/sounds`, { recursive: true })
  const manifest = { name: plugin.name, version: VERSION, description: plugin.description, author: AUTHOR, types: './types/index.d.ts' }
  if (plugin.name === 'smart-menu') delete manifest.types
  writeFileSync(`${dir}/.claude-plugin/plugin.json`, JSON.stringify(manifest, null, 2) + '\n')
  console.log('built', dir)
}

